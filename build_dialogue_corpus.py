def augment_with_variations(pairs):
    """تضخيم بتبديلات تصريفية وترتيبية."""
    augmented = []
    for q, a, cat, weight in pairs:
        augmented.append((q, a, cat, weight))
        # عكس الترتيب أحياناً (رد ← سؤال) للتماثل
        if cat in ('greeting', 'farewell', 'thanks') and weight > 50:
            augmented.append((a, q, cat + '_reverse', weight // 3))
    return augmented

