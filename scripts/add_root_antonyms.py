import json
f = json.load(open('data/fast_antonyms.json', encoding='utf-8'))
p = f['pairs']

# Root-level antonyms (الجذر ضد الجذر — يغني عن إضافة كل التصاريف)
roots = {
    'حزن': 'فرح', 'فرح': 'حزن', 'طول': 'قصر', 'قصر': 'طول',
    'كبر': 'صغر', 'صغر': 'كبر', 'قوي': 'ضعف', 'ضعف': 'قوي',
    'علم': 'جهل', 'جهل': 'علم', 'نور': 'ظلم', 'ظلم': 'نور',
    'حر': 'برد', 'برد': 'حر', 'خير': 'شر', 'شر': 'خير',
    'موت': 'حيا', 'حيا': 'موت', 'غنى': 'فقر', 'فقر': 'غنى',
    'قرب': 'بعد', 'بعد': 'قرب', 'كثر': 'قلل', 'قلل': 'كثر',
    'ارتفع': 'انخفض', 'انخفض': 'ارتفع', 'صدق': 'كذب', 'كذب': 'صدق',
    'جمل': 'قبح', 'قبح': 'جمل', 'بيض': 'سود', 'سود': 'بيض',
    'علو': 'سفل', 'سفل': 'علو', 'قدم': 'جدد', 'جدد': 'قدم',
    'سعد': 'حزن', 'سرع': 'بطؤ', 'بطؤ': 'سرع',
}

added = 0
for k, v in roots.items():
    if k not in p:
        p[k] = v
        added += 1

print(f'Added {added} root-level pairs, total: {len(p)}')

json.dump({'description': f['description'], 'pairs': p},
          open('data/fast_antonyms.json', 'w', encoding='utf-8'),
          ensure_ascii=False, indent=2)
